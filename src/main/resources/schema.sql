CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 nome VARCHAR(120) NOT NULL,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(30) NOT NULL DEFAULT 'RECEPTION',
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS medical_records (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, pet_id BIGINT NOT NULL, professional_id BIGINT NOT NULL,
 appointment_id BIGINT NULL, complaint TEXT, anamnesis TEXT, weight DOUBLE, temperature DOUBLE,
 diagnosis TEXT, conduct TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS prescriptions (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, medical_record_id BIGINT NOT NULL, medication VARCHAR(150) NOT NULL,
 dosage VARCHAR(120), frequency VARCHAR(120), duration VARCHAR(120), route VARCHAR(80), instructions TEXT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(150) NOT NULL, category VARCHAR(80),
 sku VARCHAR(80) UNIQUE, unit VARCHAR(30) DEFAULT 'un', minimum_stock DOUBLE DEFAULT 0, active BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS product_lots (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL, lot_number VARCHAR(80) NOT NULL,
 expiry_date DATE, quantity DOUBLE NOT NULL DEFAULT 0, unit_cost DECIMAL(12,2) DEFAULT 0
);
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, lot_id BIGINT NOT NULL, movement_type VARCHAR(20) NOT NULL,
 quantity DOUBLE NOT NULL, reason VARCHAR(255), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS vaccine_applications (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, pet_id BIGINT NOT NULL, vaccine_name VARCHAR(150) NOT NULL,
 application_date DATE NOT NULL, lot_number VARCHAR(80), professional_id BIGINT NOT NULL, next_dose DATE, notes TEXT
);
CREATE TABLE IF NOT EXISTS exam_requests (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, pet_id BIGINT NOT NULL, appointment_id BIGINT NULL,
 exam_name VARCHAR(150) NOT NULL, laboratory VARCHAR(150), status VARCHAR(30) NOT NULL DEFAULT 'SOLICITADO',
 result TEXT, requested_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, result_at TIMESTAMP NULL
);
CREATE TABLE IF NOT EXISTS invoices (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, tutor_id BIGINT NOT NULL, appointment_id BIGINT NULL,
 description VARCHAR(255) NOT NULL, total DECIMAL(12,2) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'ABERTA',
 payment_method VARCHAR(40), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, paid_at TIMESTAMP NULL
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, tutor_id BIGINT NULL, channel VARCHAR(30) NOT NULL,
 message TEXT NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'SIMULADA',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(60), action VARCHAR(80) NOT NULL,
 entity_name VARCHAR(80), entity_id BIGINT, details TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
